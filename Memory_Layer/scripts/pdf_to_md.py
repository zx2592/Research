def pdf_to_markdown(pdf_path, output_dir):
    """
    Converts a PDF file to a Markdown file.
    
    Args:
        pdf_path (str): Path to the source PDF file.
        output_dir (str): Directory where the Markdown file will be saved.
    """
    base_name = os.path.basename(pdf_path)
    file_name_without_ext = os.path.splitext(base_name)[0]
    md_file_path = os.path.join(output_dir, f"{file_name_without_ext}.md")
    
    print(f"Processing: {pdf_path}")
    
    # Placeholder for actual conversion logic
    # meaningful content extraction would happen here.
    content = f"# Summary of {base_name}\n\n"
    content += "> [Auto-generated by pdf_to_md.py]\n\n"
    content += "## Extracted Text\n\n"
    content += "(This is a placeholder. Install 'markitdown' or 'pdfplumber' for actual extraction.)\n"
    
    try:
        with open(md_file_path, 'w', encoding='utf-8') as f:
            f.write(content)
        print(f"Successfully converted to: {md_file_path}")
    except Exception as e:
        print(f"Error converting {pdf_path}: {e}")

def main():
    parser = argparse.ArgumentParser(description="Convert PDF reports to Markdown for the Knowledge Base.")
    parser.add_argument("input_path", help="Path to a PDF file or a directory containing PDFs.")
    parser.add_argument("--output", "-o", default="../Knowledge_Base", help="Output directory for Markdown files.")
    
    args = parser.parse_args()
    
    # Ensure output directory exists
    os.makedirs(args.output, exist_ok=True)
    
    if os.path.isfile(args.input_path):
        if args.input_path.lower().endswith('.pdf'):
            pdf_to_markdown(args.input_path, args.output)
        else:
            print("The input file is not a PDF.")
    elif os.path.isdir(args.input_path):
        for root, dirs, files in os.walk(args.input_path):
            for file in files:
                if file.lower().endswith('.pdf'):
                    full_path = os.path.join(root, file)
                    pdf_to_markdown(full_path, args.output)
    else:
        print("Invalid input path.")

if __name__ == "__main__":
    main()
